export const DEFAULT_LEGAL: Record<LegalKind, string> = { terms: TERMS, privacy: PRIVACY };


export function fillLegal(content: string, siteName: string, baseUrl: string) {
  return content.replaceAll('{{站点名称}}', siteName).replaceAll('{{网址}}', baseUrl.replace(/\/+$/, ''));
}
export async function publicLegal(kind: LegalKind, baseUrl: string): Promise<PublicLegalDTO> {
  const [legal, site] = await Promise.all([getSetting('legal'), getSettings()]);
  const doc = legal[kind];
  return { kind, title: legal.documentMeta[kind]?.title || t(kind === 'terms' ? 'legal.terms' : 'legal.privacy'), content: fillLegal(doc.content || DEFAULT_LEGAL[kind], site.siteName, baseUrl), updatedAt: doc.updatedAt || null, custom: !!doc.content };
}
export function adminLegal(legal: LegalSettings): LegalSettingsDTO {
  const doc = (kind: LegalKind) => ({ content: legal[kind].content || DEFAULT_LEGAL[kind], updatedAt: legal[kind].updatedAt || null, custom: !!legal[kind].content });
  return { terms: doc('terms'), privacy: doc('privacy'), requireAgree: legal.requireAgree, defaults: DEFAULT_LEGAL };
}
export function agreedDetail(legal: LegalSettings) {
  const version = (kind: LegalKind) => `《${LEGAL_TITLES[kind]}》（${legal[kind].updatedAt || '内置模板'}）`;
  return `已勾选同意${version('terms')}和${version('privacy')}`;
}
